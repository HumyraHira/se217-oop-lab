public class switch_case {
    public static void main(String[] args) {

        int k = 3;

        switch (k) {
            case 1:
                System.out.println("Hello");
                break;

            case 2:
                System.out.println("Good Morning");
                break;

            case 3:
                System.out.println("Good Bye");
                break;

            default:
                System.out.println("Wrong Input");
        }
    }
}
